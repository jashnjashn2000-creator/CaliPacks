/**
 * Builds cloudflare/checkout-worker/src/product-catalog.js from the website's own
 * product data (src/data/products.ts + src/data/shop-stock.ts).
 *
 * WHY: the checkout worker must price every order itself from trusted data and
 * never believe prices sent by the browser. This file is that trusted price list.
 *
 * Runs automatically before `npm run build` (see "prebuild" in package.json).
 * After a price change: rebuild the site AND redeploy the worker, so both agree.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "cloudflare/checkout-worker/src/product-catalog.js");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "smokecali-catalog-"));

function transpile(srcPath, destName) {
  let code = fs.readFileSync(srcPath, "utf8");
  code = code.replace(/from\s+["']@\/data\/shop-stock["']/g, 'from "./shop-stock.mjs"');
  const out = ts.transpileModule(code, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  });
  fs.writeFileSync(path.join(tmp, destName), out.outputText);
}

transpile(path.join(root, "src/data/shop-stock.ts"), "shop-stock.mjs");
transpile(path.join(root, "src/data/products.ts"), "products.mjs");

const mod = await import(pathToFileURL(path.join(tmp, "products.mjs")).href);
const all = mod.products;
if (!Array.isArray(all) || all.length < 10) {
  throw new Error("Product list looks wrong — catalog not written.");
}

const catalog = {};
for (const p of all) {
  if (!p.id || typeof p.price !== "number" || p.price <= 0) continue;
  catalog[p.id] = {
    name: String(p.name),
    pricePence: Math.round(p.price * 100),
    minOrder: Math.max(1, p.minOrder || 1),
    inStock: p.inStock !== false,
  };
}

const header = `/**
 * AUTO-GENERATED by scripts/generate-worker-catalog.mjs — do not edit by hand.
 * Trusted price list used by the checkout worker. Prices are in PENCE.
 * Generated from src/data/products.ts + src/data/shop-stock.ts.
 */
`;
const body = `export const PRODUCT_CATALOG = ${JSON.stringify(catalog, null, 1)};\n`;
fs.writeFileSync(outFile, header + body);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`Worker catalog written: ${Object.keys(catalog).length} products -> ${path.relative(root, outFile)}`);
